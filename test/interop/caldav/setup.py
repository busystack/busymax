#!/usr/bin/env python3
"""Fetch and verify the official Baikal asset; generate isolated QA credentials."""
import hashlib
import json
import pathlib
import secrets
import subprocess
import urllib.request
import zipfile

ROOT = pathlib.Path(__file__).resolve().parent
RUNTIME = ROOT / '.runtime'
SHA256 = '81e74df123230e863f608d228fdd7b9a1a788f60b04d37e6973c302192e83f32'


def main():
    RUNTIME.mkdir(mode=0o700, exist_ok=True)
    archive = RUNTIME / 'baikal-0.13.0.zip'
    if not archive.exists():
        urllib.request.urlretrieve(
            'https://github.com/sabre-io/Baikal/releases/download/0.13.0/baikal-0.13.0.zip', archive)
    if hashlib.sha256(archive.read_bytes()).hexdigest() != SHA256:
        raise SystemExit('Official Baikal archive checksum mismatch')
    with zipfile.ZipFile(archive) as z:
        for name in z.namelist():
            if not name.startswith('baikal/') or '..' in pathlib.PurePosixPath(name).parts:
                raise SystemExit('Unsafe archive member')
        z.extractall(RUNTIME)
    credentials_path = RUNTIME / 'credentials.json'
    if not credentials_path.exists():
        credentials_path.write_text(json.dumps({user: secrets.token_urlsafe(24) for user in ['alice', 'bob']}))
        credentials_path.chmod(0o600)
    credentials = json.loads(credentials_path.read_text())
    # SHA-256 crypt, generated by the system OpenSSL without passwords in argv.
    hashes = {user: subprocess.run(['openssl', 'passwd', '-5', '-stdin'],
                                  input=password + '\n', text=True, check=True,
                                  capture_output=True).stdout.strip()
              for user, password in credentials.items()}
    (RUNTIME / 'users').write_text(''.join(f'{user}:{hashed}\n' for user, hashed in hashes.items()))
    print('Official release verified; local disposable credentials prepared (not printed).')


if __name__ == '__main__':
    main()
