#!/usr/bin/env python3
"""Regenerate both BusyMax timezone artifacts from one verified IANA release.

Requires make, zic, Dart, and the dependencies selected by pubspec.lock.
The official timezone package and its encoder are used without modification.
"""
import base64
import gzip
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import sys
import tarfile
import tempfile
import urllib.request

VERSION = '2026f'
SHA256 = '01b4a91cec5167ed48c11e8ab78f2048cead78ce94b0cafcad0ae8c5a3044d3d'
URL = f'https://data.iana.org/time-zones/releases/tzdata{VERSION}.tar.gz'
ROOT = Path(__file__).resolve().parents[1]


def main():
    source = Path(sys.argv[1]).read_bytes() if len(sys.argv) > 1 else urllib.request.urlopen(URL).read()
    if hashlib.sha256(source).hexdigest() != SHA256:
        raise SystemExit('IANA release checksum mismatch')
    config_path = ROOT / '.dart_tool/package_config.json'
    config = json.loads(config_path.read_text())
    package = next(p for p in config['packages'] if p['name'] == 'timezone')
    from urllib.parse import urljoin, urlparse, unquote
    package_root = Path(unquote(urlparse(urljoin(config_path.as_uri(), package['rootUri'])).path))
    dart = shutil.which('dart')
    if not dart:
        raise SystemExit('Dart is required')
    with tempfile.TemporaryDirectory(prefix='busymax-iana-') as directory:
        temp = Path(directory)
        archive = temp / 'source.tar.gz'
        archive.write_bytes(source)
        with tarfile.open(archive) as tar:
            tar.extractall(temp, filter='data')
        if (temp / 'version').read_text().strip() != VERSION:
            raise SystemExit('IANA release version mismatch')
        subprocess.run(['make', '-C', str(temp), 'rearguard.zi'], check=True)
        zones = temp / 'zoneinfo'
        zones.mkdir()
        subprocess.run(['zic', '-b', 'fat', '-d', str(zones), str(temp / 'rearguard.zi')], check=True)
        tzf = temp / 'all.tzf'
        command = [dart, f'--packages={config_path}']
        subprocess.run([*command, str(package_root / 'tool/encode_tzf.dart'), '--zoneinfo', str(zones),
                        '--output-all', str(tzf), '--output-common', str(temp / 'common.tzf'),
                        '--output-10y', str(temp / '10y.tzf')], check=True, stdout=subprocess.DEVNULL)
        packed = base64.b64encode(gzip.compress(tzf.read_bytes(), mtime=0)).decode('ascii')
        output = ROOT / f'lib/src/core/time/iana_data_{VERSION}.dart'
        header = (f'// Generated by tool/refresh_time_zone_data.py; do not edit.\n'
                  f'// Official IANA source: {URL}\n// SHA-256: {SHA256}\n'
                  '// Encoded with the official, unmodified timezone package encoder.\n'
                  f"const ianaTimeZoneVersion = '{VERSION}';\n"
                  f"const ianaTimeZoneSourceSha256 = '{SHA256}';\n"
                  'const ianaTimeZoneData =\n')
        output.write_text(header + '\n'.join(f"    '{packed[i:i+76]}'" for i in range(0, len(packed), 76)) + ';\n')
        continuation = ROOT / f'lib/src/core/time/tz_continuations_{VERSION}.dart'
        subprocess.run([*command, str(ROOT / 'tool/generate_tz_continuations.dart'), str(zones),
                        str(tzf), str(continuation)], check=True)
        subprocess.run([dart, 'format', str(output), str(continuation)], check=True)


if __name__ == '__main__':
    main()
